def sample_scenes(rng, n, q_start, q_goal, robot, robot_coll, dof):
    """Obstacles are anchored *on* the straight-line EE path, then offset.

    This is the crux of identifiability.  If the obstacle never blocks the seed
    path the collision feature is inactive, x*(theta) is the straight line for
    every theta, and no method -- however good its gradients -- can recover the
    weights.  Anchoring on the path and varying the offset/radius makes the
    collision term active to differing degrees across contexts, which is exactly
    the variation the weights are identified from.
    """
    starts, goals = [], []
    for _ in range(n):
        jitter = rng.normal(scale=0.10, size=dof)
        starts.append(np.asarray(q_start) + jitter)
        goals.append(np.asarray(q_goal) - jitter)
    starts, goals = np.stack(starts), np.stack(goals)

    ee_index = robot.links.names.index(EE_LINK)
    centers, radii = [], []
    for i in range(n):
        scene_i = Scene(
            q_start=jnp.asarray(starts[i]),
            q_goal=jnp.asarray(goals[i]),
            obs_center=jnp.zeros(3),
            obs_radius=jnp.ones(1),
        )
        q_seed = unpack(straight_line_seed(scene_i, dof), scene_i, dof)
        p = np.asarray(ee_positions(q_seed, robot, ee_index))
        t = rng.integers(N_TIMESTEPS // 3, 2 * N_TIMESTEPS // 3)
        r = rng.uniform(0.08, 0.14)
        # Offset the obstacle just about one radius off the path: a little less
        # and it blocks, a little more and it is clear.  Anchoring it *on* the
        # path instead leaves the seed deeply penetrating in every context, which
        # saturates the collision feature and destroys the tradeoff.
        direction = rng.normal(size=3)
        direction /= np.linalg.norm(direction)
        centers.append(p[t] + direction * (r + rng.uniform(-0.05, 0.10)))
        radii.append(np.array([r]))

    return Scene(
        q_start=jnp.asarray(starts),
        q_goal=jnp.asarray(goals),
        obs_center=jnp.asarray(np.stack(centers)),
        obs_radius=jnp.asarray(np.stack(radii)),
    )


def calibrate_scales(scenes, robot, robot_coll, dof, collinear, key, n_probe=16, jitter=0.15):
    """Whiten features so weight recovery does not just measure feature scaling.

    Calibrate on *randomly perturbed* trajectories, never on the straight-line
    seed: the seed has exactly zero acceleration, so a seed-based scale for the
    smoothness feature collapses to the numerical floor and silently applies an
    enormous weight to it, pinning x*(theta) to the straight line for every theta.
    """

    def raw(scene, k):
        x0 = straight_line_seed(scene, dof)
        x = x0 + jitter * jax.random.normal(k, x0.shape)
        return features(x, scene, robot, robot_coll, dof, collinear)

    keys = jax.random.split(key, n_probe)
    vals = jax.vmap(jax.vmap(raw, in_axes=(None, 0)), in_axes=(0, None))(scenes, keys)
    vals = vals.reshape(-1, K)
    scales = jnp.mean(jnp.abs(vals), axis=0)
    assert bool(jnp.all(scales > 1e-8)), f"degenerate feature scale: {scales}"
    return scales


