N_TIMESTEPS = 24  # overridden by --n-timesteps
EE_LINK = "panda_hand"
CLEARANCE_MARGIN = 0.05  # [m] distance at which the collision feature turns on
SOFTMIN_TAU = 0.02  # [m] temperature of the soft-min over collision pairs
SOFTNESS = 60.0  # smoothing of the collision hinge; keeps the Hessian continuous

FEATURE_NAMES = ("effort", "collision", "smooth")
K = len(FEATURE_NAMES)


@jax.tree_util.register_dataclass
@dataclasses.dataclass(frozen=True)
class Scene:
    """A single demonstration context: fixed endpoints plus one spherical obstacle."""

    q_start: jnp.ndarray  # (dof,)
    q_goal: jnp.ndarray  # (dof,)
    obs_center: jnp.ndarray  # (3,)
    obs_radius: jnp.ndarray  # (1,)


def make_world(scene: Scene):
    return pk.collision.Sphere.from_center_and_radius(
        scene.obs_center[None, :], scene.obs_radius
    )


def unpack(x_flat, scene, dof):
    """Interior waypoints -> full trajectory with the endpoints clamped on."""
    interior = x_flat.reshape(N_TIMESTEPS - 2, dof)
    return jnp.concatenate(
        [scene.q_start[None, :], interior, scene.q_goal[None, :]], axis=0
    )


def residuals(x_flat, scene, robot, robot_coll, dof, collinear: bool):
    """Per-feature residual vectors r_k, with phi_k = ||r_k||^2.

    The features are expressed as residuals rather than scalars so the inner
    problem is a weighted nonlinear least-squares problem.  Its Gauss-Newton
    Hessian sum_k theta_k J_k^T J_k is positive semidefinite by construction,
    which is what makes x*(theta) a well-defined, locally smooth function of
    theta.  With a general (indefinite) Hessian the solver stalls in
    negative-curvature regions and the iterate it returns jumps discontinuously
    under infinitesimal changes of theta -- measured here at up to 0.3 rad of
    jump for a 1e-4 change in a weight, which destroys both finite differences
    and the implicit-function theorem.
    """
    q = unpack(x_flat, scene, dof)

    r_effort = (q[1:] - q[:-1]).reshape(-1)
    r_smooth = (q[2:] - 2.0 * q[1:-1] + q[:-2]).reshape(-1)

    # Sphere-level clearance, computed analytically rather than through
    # `compute_world_collision_distance`.  That helper reduces over the spheres
    # within each link with a hard max, and a hard max/min is nondifferentiable
    # exactly where the nearest sphere switches identity -- which is the ridge
    # the optimizer drives the solution onto.  The result is a cost that
    # converges while its gradient never vanishes: the solve stalls at a
    # non-stationary point (measured: only ~53% of scenes reached ||grad||<1e-5
    # even at 400 iterations), and both the implicit function theorem and finite
    # differences become invalid there.  Sphere-vs-sphere distance is smooth in
    # closed form, so every reduction here is a soft-min instead.
    coll = robot_coll.at_config(robot, q)  # (T, S, N) spheres
    centers = coll.pose.translation()  # (T, S, N, 3)
    radii = coll.radius  # (T, S, N)
    d = (
        jnp.linalg.norm(centers - scene.obs_center, axis=-1)
        - radii
        - scene.obs_radius[0]
    )
    d = d.reshape(d.shape[0], -1)  # (T, S*N)
    d_min = -SOFTMIN_TAU * jax.scipy.special.logsumexp(-d / SOFTMIN_TAU, axis=-1)
    r_coll = jax.nn.softplus(SOFTNESS * (CLEARANCE_MARGIN - d_min)) / SOFTNESS

    if collinear:
        # Deliberately near-degenerate control: a second copy of the velocity
        # residual.  Every method should fail to separate the two, and the
        # recovered weights should be flat along their difference.
        r_smooth = r_effort

    return (r_effort, r_coll, r_smooth)


def features(x_flat, scene, robot, robot_coll, dof, collinear: bool):
    """phi(x, c) in R^K, whitened by fixed nominal scales set in `calibrate_scales`."""
    rs = residuals(x_flat, scene, robot, robot_coll, dof, collinear)
    return jnp.stack([jnp.sum(r**2) for r in rs])


def ee_positions(q, robot, ee_index):
    return robot.forward_kinematics(q)[..., ee_index, 4:7]


# ---------------------------------------------------------------------------
# Inner solver: damped Newton with a fixed iteration count
# ---------------------------------------------------------------------------


def make_inner(robot, robot_coll, dof, scales, collinear, n_newton, damping,
               n_unroll_tail=4, adjoint_ridge=1e-9):
    def cost(x_flat, theta, scene):
        phi = features(x_flat, scene, robot, robot_coll, dof, collinear) / scales
        return jnp.dot(theta, phi)

    grad_x = jax.grad(cost, argnums=0)
    hess_x = jax.hessian(cost, argnums=0)

    def gn_system(x, theta, scene):
        """Gauss-Newton gradient and PSD Hessian of sum_k theta_k ||r_k||^2 / s_k."""
        def res_cat(xx):
            rs = residuals(xx, scene, robot, robot_coll, dof, collinear)
            w = jnp.sqrt(theta / scales)
            return jnp.concatenate([wk * r for wk, r in zip(w, rs)])

        r = res_cat(x)
        J = jax.jacobian(res_cat)(x)
        return 2.0 * J.T @ r, 2.0 * J.T @ J

    def step(carry, theta, scene):
        """One damped Gauss-Newton iteration with an accept/reject guard.

        J^T J is PSD by construction, so the step direction is always a descent
        direction and the iteration converges to a genuine stationary point --
        which is the precondition for both finite differences and the implicit
        function theorem to mean anything.
        """
        x, lam = carry
        f = cost(x, theta, scene)
        g, H = gn_system(x, theta, scene)
        n = H.shape[0]
        H = H + lam * (jnp.trace(H) / n + 1.0) * jnp.eye(n, dtype=H.dtype)
        dx = jnp.linalg.solve(H, g)
        dx = jnp.where(jnp.isfinite(dx), dx, 0.0)
        x_new = x - dx
        ok = cost(x_new, theta, scene) <= f
        x = jnp.where(ok, x_new, x)
        # Cap the damping. With a PSD Gauss-Newton Hessian a small lambda already
        # guarantees a descent direction, so an unbounded cap only enables a death
        # spiral: near the optimum the cost decrease drops below floating-point
        # noise, every step is rejected, lambda ratchets up, steps shrink, and the
        # solver freezes with a large residual gradient (measured: cost converged
        # to 7 digits while ||grad|| stalled at 1.3e-2 and lambda reached 1.4e4).
        lam = jnp.clip(jnp.where(ok, lam * 0.3, lam * 3.0), 1e-10, 1e4)
        return (x, lam)

    def newton(x0, theta, scene):
        carry = jax.lax.fori_loop(
            0, n_newton, lambda _, c: step(c, theta, scene), (x0, damping)
        )
        return carry[0]

    def step_plain(x, lam, theta, scene):
        """Ungated Gauss-Newton step, used for the differentiable unroll tail.

        The gated step returns its input unchanged on a rejected iteration, and
        since the unroll head is under stop_gradient that makes the truncated
        unrolled gradient exactly zero -- silently, and most often right at
        convergence where rejections are common.
        """
        g, H = gn_system(x, theta, scene)
        n = H.shape[0]
        H = H + lam * (jnp.trace(H) / n + 1.0) * jnp.eye(n, dtype=H.dtype)
        return x - jnp.linalg.solve(H, g)

    step_plain_remat = jax.checkpoint(step_plain)

    def solve_unrolled(x0, theta, scene):
        """Truncated unrolling: the last `n_unroll_tail` steps carry gradients.

        Backpropagating through all `n_newton` steps is not memory-feasible --
        each step holds a dense inner Jacobian built from a full FK graph over
        the horizon, and the reverse pass exceeds device memory even with
        rematerialization.  That limitation is itself a result: it is exactly the
        cost the implicit adjoint avoids, since it needs only the final iterate.
        """
        n_head = max(0, n_newton - n_unroll_tail)
        x, lam = jax.lax.stop_gradient(
            jax.lax.fori_loop(0, n_head, lambda _, c: step(c, theta, scene), (x0, damping))
        )
        for _ in range(n_newton - n_head):
            x = step_plain_remat(x, lam, theta, scene)
        return x

    def inner_grad_norm(x0, theta, scene):
        """Stationarity residual of the inner solve -- implicit diff assumes ~0."""
        return jnp.linalg.norm(grad_x(newton(x0, theta, scene), theta, scene))

    # -- implicit: adjoint through the stationarity condition -------------------
    @jax.custom_vjp
    def solve_implicit(x0, theta, scene):
        return newton(x0, theta, scene)

    def _fwd(x0, theta, scene):
        xs = jax.lax.stop_gradient(newton(x0, theta, scene))
        return xs, (xs, theta, scene)

    def _bwd(res, g_out):
        xs, theta, scene = res
        H = hess_x(xs, theta, scene)
        # Ridge only for numerical invertibility.  Reusing the LM damping here
        # would be a bug: that damping exists to make the *forward* step safe,
        # and it is many orders of magnitude larger than what conditioning needs,
        # so it biases H^{-1} and corrupts the adjoint.
        n = H.shape[0]
        H = H + adjoint_ridge * (jnp.trace(H) / n + 1.0) * jnp.eye(n, dtype=H.dtype)
        # dx*/dtheta = -H^{-1} B, so the cotangent is -B^T H^{-T} g_out.
        u = jnp.linalg.solve(H.T, g_out)
        _, vjp_theta = jax.vjp(lambda th: grad_x(xs, th, scene), theta)
        (g_theta,) = vjp_theta(u)
        zero_scene = jax.tree.map(jnp.zeros_like, scene)
        return jnp.zeros_like(xs), -g_theta, zero_scene

    solve_implicit.defvjp(_fwd, _bwd)

    return cost, grad_x, solve_unrolled, solve_implicit, inner_grad_norm


def straight_line_seed(scene, dof):
    alphas = jnp.linspace(0.0, 1.0, N_TIMESTEPS)[1:-1, None]
    return ((1 - alphas) * scene.q_start + alphas * scene.q_goal).reshape(-1)


