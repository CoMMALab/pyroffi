def make_outer(robot, robot_coll, dof, ee_index, solver, scenes, demos, seeds):
    """L(z) over all contexts, with theta = softmax(z)."""

    def per_scene(z, scene, demo, x0):
        theta = jax.nn.softmax(z)
        xs = solver(x0, theta, scene)
        p = ee_positions(unpack(xs, scene, dof), robot, ee_index)
        p_demo = ee_positions(demo, robot, ee_index)
        return jnp.mean(jnp.sum((p - p_demo) ** 2, axis=-1))

    def loss(z):
        vals = jax.vmap(per_scene, in_axes=(None, 0, 0, 0))(z, scenes, demos, seeds)
        return jnp.mean(vals)

    return loss


