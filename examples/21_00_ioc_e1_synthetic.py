"""E1: synthetic identifiability experiment for differentiable inverse optimal control.

Ground-truth cost weights are known.  Demonstrations are generated by solving a
kinematic reach-with-obstacle trajectory optimization under those weights; each
method must recover them from the demonstrated trajectories alone.

Inner problem (per context c, interior waypoints x = q_{1..T-2} free, endpoints fixed):

    x*(theta, c) = argmin_x  sum_k theta_k * phi_k(x, c),      theta in the simplex

Outer problem:

    min_z  L(z) = sum_i || p_ee(x*(softmax(z), c_i)) - p_ee(x_demo_i) ||^2

Methods compared:
  implicit   -- custom_vjp adjoint through the inner KKT point (1 solve / step)
  unrolled   -- reverse-mode through the inner Newton iterations
  fd         -- finite differences on L(z) (K+1 solves / step)
  cmaes      -- derivative-free search on z (population solves / step)
  kkt        -- feature-matching residual ||grad_x J_theta(x_demo)||^2 (0 solves)

Run under float64: the implicit adjoint needs an accurate inner Hessian.

    XLA_PYTHON_CLIENT_PREALLOCATE=false JAX_ENABLE_X64=1 CUDA_VISIBLE_DEVICES=0 \
        python examples/21_00_ioc_e1_synthetic.py
"""

