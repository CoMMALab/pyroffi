def adam(grad_fn, z0, n_steps, lr, solves_per_step):
    """Adam on z, returning the best iterate seen, not the last one.

    CMA-ES reports its best-ever candidate, so returning Adam's final iterate
    would compare a noisy last step against a curated best and make the gradient
    methods look worse than they are -- especially at high demonstration noise,
    where the outer landscape is rough.  Both now report best-so-far.  The loss
    at z_t is already computed by grad_fn, so this costs no extra solves.
    """
    z, m, v = z0, jnp.zeros_like(z0), jnp.zeros_like(z0)
    history = []
    best_val, best_z = np.inf, z0
    for t in range(1, n_steps + 1):
        val, g = grad_fn(z)
        fval = float(val)
        if fval < best_val:
            best_val, best_z = fval, z
        m = 0.9 * m + 0.1 * g
        v = 0.999 * v + 0.001 * g**2
        mh, vh = m / (1 - 0.9**t), v / (1 - 0.999**t)
        z = z - lr * mh / (jnp.sqrt(vh) + 1e-8)
        history.append((t * solves_per_step, fval))
    return best_z, history


def fd_grad_fn(loss, eps):
    def grad_fn(z):
        val = loss(z)
        g = []
        for k in range(z.shape[0]):
            e = jnp.zeros_like(z).at[k].set(eps)
            g.append((loss(z + e) - val) / eps)
        return val, jnp.stack(g)

    return grad_fn


def cma_es(loss, z0, n_gens, sigma0, seed):
    """Compact (mu/mu_w, lambda)-CMA-ES; avoids a new dependency on `cma`."""
    n = z0.shape[0]
    lam = 4 + int(3 * np.log(n))
    mu = lam // 2
    w = np.log(mu + 0.5) - np.log(np.arange(1, mu + 1))
    w /= w.sum()
    mueff = 1.0 / np.sum(w**2)
    cc = (4 + mueff / n) / (n + 4 + 2 * mueff / n)
    cs = (mueff + 2) / (n + mueff + 5)
    c1 = 2 / ((n + 1.3) ** 2 + mueff)
    cmu = min(1 - c1, 2 * (mueff - 2 + 1 / mueff) / ((n + 2) ** 2 + mueff))
    damps = 1 + 2 * max(0, np.sqrt((mueff - 1) / (n + 1)) - 1) + cs
    chiN = np.sqrt(n) * (1 - 1 / (4 * n) + 1 / (21 * n**2))

    rng = np.random.default_rng(seed)
    mean = np.array(z0, dtype=np.float64)
    C = np.eye(n)
    pc, ps = np.zeros(n), np.zeros(n)
    sigma = sigma0
    history, n_solves = [], 0
    best = (np.inf, mean)

    for gen in range(1, n_gens + 1):
        d, B = np.linalg.eigh(C)
        d = np.sqrt(np.maximum(d, 1e-12))
        Z = rng.standard_normal((lam, n))
        Y = Z @ (B * d).T
        X = mean + sigma * Y
        fs = np.array([float(loss(jnp.asarray(x))) for x in X])
        n_solves += lam
        order = np.argsort(fs)
        if fs[order[0]] < best[0]:
            best = (fs[order[0]], X[order[0]].copy())
        Yw = w @ Y[order[:mu]]
        mean = mean + sigma * Yw

        Cinv_half = (B / d) @ B.T
        ps = (1 - cs) * ps + np.sqrt(cs * (2 - cs) * mueff) * (Cinv_half @ Yw)
        hsig = np.linalg.norm(ps) / np.sqrt(1 - (1 - cs) ** (2 * gen)) / chiN < 1.4 + 2 / (n + 1)
        pc = (1 - cc) * pc + hsig * np.sqrt(cc * (2 - cc) * mueff) * Yw
        Ymu = Y[order[:mu]]
        C = (
            (1 - c1 - cmu) * C
            + c1 * (np.outer(pc, pc) + (1 - hsig) * cc * (2 - cc) * C)
            + cmu * (Ymu.T * w) @ Ymu
        )
        sigma *= np.exp((cs / damps) * (np.linalg.norm(ps) / chiN - 1))
        history.append((n_solves, float(fs[order[0]])))

    return jnp.asarray(best[1]), history


def kkt_fit(grad_x, scenes, demos, dof, n_steps=400, lr=0.05):
    """Feature matching: min_theta || sum_k theta_k grad_x phi_k(x_demo) ||^2.

    Uses zero forward trajectory-optimization solves.
    """
    e = jnp.eye(K)

    def stacked_B(scene, demo):
        x_demo = demo[1:-1].reshape(-1)
        cols = [grad_x(x_demo, e[k], scene) for k in range(K)]
        return jnp.stack(cols, axis=-1)  # (n_x, K)

    Bs = jax.vmap(stacked_B)(scenes, demos)
    G = jnp.einsum("bik,bil->kl", Bs, Bs) / Bs.shape[0]

    def resid(z):
        theta = jax.nn.softmax(z)
        return theta @ G @ theta

    grad_fn = jax.jit(jax.value_and_grad(resid))
    z, _ = adam(lambda zz: grad_fn(zz), jnp.zeros(K), n_steps, lr, 0)
    return z, G


