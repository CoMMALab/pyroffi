def simplex_metrics(theta_hat, theta_star):
    l1 = float(jnp.sum(jnp.abs(theta_hat - theta_star)))
    cos = float(
        jnp.dot(theta_hat, theta_star)
        / (jnp.linalg.norm(theta_hat) * jnp.linalg.norm(theta_star))
    )
    return l1, cos


def evaluate(z, solver, cost, robot, dof, ee_index, scenes, demos, seeds, theta_star):
    theta = jax.nn.softmax(z)

    def one(scene, demo, x0):
        x_hat = solver(x0, theta, scene)
        x_star = solver(x0, theta_star, scene)
        q_hat = unpack(x_hat, scene, dof)
        regret = cost(x_hat, theta_star, scene) - cost(x_star, theta_star, scene)
        ee_rmse = jnp.sqrt(
            jnp.mean(
                jnp.sum(
                    (ee_positions(q_hat, robot, ee_index) - ee_positions(demo, robot, ee_index))
                    ** 2,
                    axis=-1,
                )
            )
        )
        return regret, ee_rmse

    regret, ee_rmse = jax.vmap(one)(scenes, demos, seeds)
    l1, cos = simplex_metrics(theta, theta_star)
    return {
        "theta_hat": [float(t) for t in theta],
        "theta_l1": l1,
        "theta_cos": cos,
        "regret": float(jnp.mean(regret)),
        "ee_rmse": float(jnp.mean(ee_rmse)),
    }


