"""E3 -- fit wide, find the identifiable subspace, refit on it.

Question
--------
When the demonstrations cannot resolve every cost direction (r < K), does
restricting the refit to the identifiable subspace turn a poor demonstration
into a GENERALIZATION cost rather than a RECONSTRUCTION cost?

A large reconstruction error is the part that should not happen: the demo was
generated by this model at `config.Z_TRAJOPT_STAR`, so the ground truth
reproduces it exactly, and a fit that cannot get near it is an optimization
failure rather than an information failure.  The information content of a poor
demonstration should show up as an unidentifiable SUBSPACE -- bad transfer to a
scene the demo never covered -- not as an inability to reproduce the trajectory
in front of it.

Procedure: `iosp.fit.procedure.run_procedure`, which is stages 1-5 of
`THEORY_IDENTIFIABLE_REFIT.md` and is shared with every other path-A
experiment.  Model: `iosp.fit.parametric.build_parametric`.

Deliberately NOT anchored
-------------------------
Runs on the UNANCHORED scene, the one whose transport EE path clears the
obstacle by 0.091 m so `transport.clearance` sits in its flat off-region.  That
is the point: this experiment is about not having to curate the demonstration.

Reproduce
---------
    CUDA_VISIBLE_DEVICES=<idx> XLA_PYTHON_CLIENT_PREALLOCATE=false \\
        python -m iosp.experiments.e3_identifiable_refit

    --space joint       score the outer loss in configuration space (see E7)
    --scene-b-scale 2   push the held-out scene further from the fit scene
    --steps / --lr      outer budget (defaults from `iosp.config`)

Runtime ~30 min warm, ~55 min cold; the jacrev+SVD for the Gram is ~11-27 min
of that.  Watch the stationarity screen it prints first: a NOT CONVERGED line
means the spectrum below it is not trustworthy.
"""

import argparse

from iosp import config

config.enable_compilation_cache()

from iosp.fit.parametric import build_parametric
from iosp.fit.procedure import _report, run_procedure


def main(seed=0, n_iters=config.N_ITERS, n_steps=config.N_STEPS, lr=config.LR,
         space="ee", scene_b_scale=1.0):
    print("Path A (known cost library, K=9) on the UNANCHORED scene...", flush=True)
    built = build_parametric(seed=seed, n_iters=n_iters, space=space,
                             scene_b_scale=scene_b_scale)
    res = run_procedure(built, "path A (parametric)", n_steps=n_steps, lr=lr)
    _report(res)
    return res


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--n-iters", type=int, default=config.N_ITERS)
    ap.add_argument("--steps", type=int, default=config.N_STEPS)
    ap.add_argument("--lr", type=float, default=config.LR)
    ap.add_argument("--space", default="ee", choices=("ee", "joint"))
    ap.add_argument("--scene-b-scale", type=float, default=1.0)
    a = ap.parse_args()
    main(seed=a.seed, n_iters=a.n_iters, n_steps=a.steps, lr=a.lr,
         space=a.space, scene_b_scale=a.scene_b_scale)
